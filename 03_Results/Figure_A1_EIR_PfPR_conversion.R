#################################
# Supplementary Figure S3:
# EIR–PfPR conversion
#
# Created: September 2026
#
# Purpose:
#   Show the relationship between annual entomological
#   inoculation rate (EIR) and parasite prevalence (PfPR)
#   under the 2022 pre-intervention scenario without LLIN use.
#
#   This figure provides the EIR thresholds corresponding
#   to the PfPR categories used throughout the analysis.
#
# Data:
#   OpenMalaria simulation outputs stored in:
#   02_Simulation_Data/OpenMalaria_simulation_data.sqlite
#
#   Scenario information stored in:
#   02_Simulation_Data/scenarios.rds
#
# This script is stand-alone and does not depend on outputs
# generated by the Figure 2 script.
#################################


# ============================================================
# 1. PACKAGES
# ============================================================

library(tidyverse)
library(RSQLite)
library(DBI)
library(here)
library(scales)
library(ragg)


# ============================================================
# 2. LOAD SIMULATION DATA
# ============================================================

db_file <- here(
  "02_Simulation_Data",
  "OpenMalaria_simulation_data.sqlite"
)

if (!file.exists(db_file)) {
  stop(
    "SQLite database not found: ",
    db_file
  )
}

conn <- DBI::dbConnect(
  RSQLite::SQLite(),
  db_file
)

simulation_results <- DBI::dbReadTable(
  conn,
  "om_results"
)

DBI::dbDisconnect(conn)


# ============================================================
# 3. LOAD SCENARIO INFORMATION
# ============================================================

scenario_file <- here(
  "02_Simulation_Data",
  "scenarios.rds"
)

if (!file.exists(scenario_file)) {
  stop(
    "Scenario file not found: ",
    scenario_file
  )
}

scenario_data <- readRDS(
  scenario_file
) %>%
  mutate(
    scenario_id = ID
  )


# ============================================================
# 4. COMBINE SIMULATION AND SCENARIO DATA
# ============================================================

openmalaria_data <- simulation_results %>%
  
  left_join(
    scenario_data,
    by = "scenario_id"
  ) %>%
  
  mutate(
    year = lubridate::year(
      as.Date(date)
    )
  )


# ============================================================
# 5. PREPARE EIR–PfPR CONVERSION DATA
# ============================================================
#
# Baseline conditions:
#
#   Year:                 2022
#   LLIN usage:           0%
#   Population:           LLIN non-users
#
# At 0% LLIN usage, the non-user population represents the
# population under the no-LLIN baseline scenario.
#
# The mean and 95% simulation interval are calculated across
# simulation seeds for each EIR.
# ============================================================

figureA1_conversion_data <- openmalaria_data %>%
  
  filter(
    year == 2022,
    futNetcovstart2023 == 0,
    age_group == "0-100"
  ) %>%
  
  group_by(
    EIR
  ) %>%
  
  summarise(
    
    mean_PfPR =
      mean(
        prevalenceRate,
        na.rm = TRUE
      ),
    
    lower_95_PfPR =
      quantile(
        prevalenceRate,
        0.025,
        na.rm = TRUE
      ),
    
    upper_95_PfPR =
      quantile(
        prevalenceRate,
        0.975,
        na.rm = TRUE
      ),
    
    .groups = "drop"
  ) %>%
  
  arrange(
    EIR
  )


# ============================================================
# 6. CREATE EIR–PfPR CONVERSION PLOT
# ============================================================

theme_pub <- function(base_size = 10) {
  
  theme_bw(
    base_size = base_size,
    base_family = "Arial"
  ) +
    theme(
      # Overall text
      text = element_text(
        family = "Arial",
        colour = "black"
      ),
      
      # Legend
      legend.position = "bottom",
      legend.direction = "horizontal",
      legend.title = element_blank(),
      legend.text = element_text(
        size = base_size - 1
      ),
      legend.key = element_blank(),
      legend.key.height = unit(0.5, "lines"),
      legend.spacing.x = unit(0.25, "cm"),
      
      # Facets
      strip.text = element_text(
        face = "bold",
        size = base_size,
        colour = "black"
      ),
      strip.background = element_rect(
        fill = "white",
        colour = NA
      ),
      
      # Grid
      panel.grid.major.x = element_blank(),
      panel.grid.major.y = element_line(
        colour = "grey85",
        linewidth = 0.25
      ),
      panel.grid.minor = element_blank(),
      panel.spacing = unit(0.8, "lines"),
      
      # Axes
      axis.title = element_text(
        face = "bold",
        size = base_size,
        colour = "black"
      ),
      axis.text = element_text(
        colour = "black",
        size = base_size - 1
      ),
      
      # Panel border
      panel.border = element_rect(
        colour = "black",
        linewidth = 0.5
      ),
      
      # Axis ticks
      axis.ticks = element_line(
        linewidth = 0.4,
        colour = "black"
      ),
      
      # Do not put the manuscript figure title inside the plot
      plot.title = element_blank(),
      
      # Useful for multi-panel labels such as A and B
      plot.tag = element_text(
        family = "Arial",
        face = "bold",
        size = base_size + 1,
        colour = "black"
      ),
      
      # Small outer border while avoiding excessive whitespace
      plot.margin = margin(5, 5, 5, 5),
      
      # White background
      plot.background = element_rect(
        fill = "white",
        colour = NA
      )
    )
}


figureA1 <- ggplot(
  figureA1_conversion_data,
  aes(
    x = EIR,
    y = mean_PfPR
  )
) +
  
  geom_ribbon(
    aes(
      ymin = lower_95_PfPR,
      ymax = upper_95_PfPR
    ),
    fill = "black",
    alpha = 0.2
  ) +
  
  geom_line(
    linewidth = 0.8,
    colour = "black"
  ) +
  
  geom_point(
    size = 1.5,
    colour = "black"
  ) +
  
  scale_x_continuous(
    trans = "log10",
    breaks = c( 1, 2, 8, 20, 50, 80, 100),
    labels = c( 1, 2, 8, 20, 50, 80, 100)
  ) +
  
  scale_y_continuous(
    labels = scales::percent_format(
      accuracy = 1
    )
  ) +
  
  labs(
    x = "Entomological inoculation rate (EIR; log10 scale)",
    y = expression(
      italic(Pf)*"PR (2022 baseline, no LLIN)"
    )
  ) +
  
  theme_pub()


figureA1

# ============================================================
# 7. ADD PfPR CATEGORY THRESHOLDS
# ============================================================
#
# PfPR categories used in the analysis:
#
#   Low:       <10%
#   Moderate:  10–35%
#   High:      >35%
#
# The corresponding EIR thresholds are:
#
#   EIR = 2  -> PfPR approximately 10%
#   EIR = 8  -> PfPR approximately 35%
#
# The 47% line is retained from the original figure as an
# additional visual reference.
# ============================================================

figureA1 <- figureA1 +
  
  geom_hline(
    yintercept = c(
      0.10,
      0.35,
      0.47
    ),
    linetype = "dashed",
    colour = "grey50",
    linewidth = 0.3
  ) +
  
  geom_vline(
    xintercept = c(
      2,
      8
    ),
    linetype = "dotted",
    colour = "grey60",
    linewidth = 0.3
  ) +
  
  annotate(
    "text",
    x = 33,
    y = 0.07,
    label = "Low PfPR (<10%)",
    hjust = 0,
    size = 4,
    colour = "#2A6EBB"
  ) +
  
  annotate(
    "text",
    x = 33,
    y = 0.31,
    label = "Moderate PfPR (10–35%)",
    hjust = 0,
    size = 4,
    colour = "#F0AB00"
  ) +
  
  annotate(
    "text",
    x = 33,
    y = 0.41,
    label = "High PfPR (>35%)",
    hjust = 0,
    size = 4,
    colour = "#C50084"
  )


# ============================================================
# 8. DISPLAY FIGURE
# ============================================================

figureA1


